-- Yarıda bırakılan eser taslakları: gizli "vazgeçen" rozetleri + meta rozet.
-- 202610140002_special_badges.sql sonrasında çalıştırılır.

-- 1) Yarım bırakma kayıtları: istemci doğrudan yazamaz, yalnızca RPC yazar.
create table if not exists public.draft_abandons (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('writing', 'drawing', 'photo', 'video', 'music')),
  created_at timestamptz not null default now()
);
alter table public.draft_abandons enable row level security;
revoke all on public.draft_abandons from anon, authenticated;
create index if not exists draft_abandons_user_kind_idx on public.draft_abandons (user_id, kind);

-- 2) Yarım bırakma kaydı + rozet kontrolü.
--    60 saniyelik pencerede aynı tür tekrar sayılmaz (çift sekme/yanlışlıkla tetiklenme).
--    Her türde 5 yarım bırakma o türün gizli rozetini açar; beş tür tamamlanırsa
--    'ilham_eksikligi' meta rozeti kazanılır.
create or replace function public.record_draft_abandon(p_kind text)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  cnt int;
  ins_key text;
  awarded text[] := '{}';
begin
  if uid is null then
    raise exception 'Giriş gerekli.' using errcode = '42501';
  end if;
  if p_kind not in ('writing', 'drawing', 'photo', 'video', 'music') then
    raise exception 'Geçersiz tür.';
  end if;
  if exists (select 1 from public.draft_abandons
             where user_id = uid and kind = p_kind
               and created_at > now() - interval '60 seconds') then
    return jsonb_build_object('ok', true, 'counted', false);
  end if;

  insert into public.draft_abandons (user_id, kind) values (uid, p_kind);
  select count(*) into cnt from public.draft_abandons where user_id = uid and kind = p_kind;

  if cnt >= 5 then
    insert into public.user_badges (user_id, badge_key)
      values (uid, 'abandon_' || p_kind)
      on conflict do nothing
      returning badge_key into ins_key;
    if ins_key is not null then awarded := awarded || ('abandon_' || p_kind); end if;
  end if;

  if (select count(*) from public.user_badges
      where user_id = uid and badge_key like 'abandon\_%' escape '\') >= 5 then
    insert into public.user_badges (user_id, badge_key)
      values (uid, 'ilham_eksikligi')
      on conflict do nothing;
    if found then awarded := awarded || 'ilham_eksikligi'; end if;
  end if;

  return jsonb_build_object('ok', true, 'counted', true, 'total', cnt, 'awarded', awarded);
end;
$$;
revoke all on function public.record_draft_abandon(text) from public;
grant execute on function public.record_draft_abandon(text) to authenticated;

notify pgrst, 'reload schema';
