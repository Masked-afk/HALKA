-- Ad değişikliği korumaları: geçmiş kaydı, cooldown, eski ad rezervasyonu,
-- yasaklı terim filtresi ve admin'in eski adla kullanıcı bulması.
-- 202610140003_abandoned_badges.sql sonrasında çalıştırılır.

-- 1) Değişiklik geçmişi (yalnızca admin okur)
create table if not exists public.name_changes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  field text not null check (field in ('username', 'display_name')),
  old_value text,
  new_value text,
  created_at timestamptz not null default now()
);
alter table public.name_changes enable row level security;
revoke all on public.name_changes from anon, authenticated;
grant select on public.name_changes to authenticated;

drop policy if exists "Admins read name changes" on public.name_changes;
create policy "Admins read name changes"
  on public.name_changes for select to authenticated
  using (public.is_current_user_admin());

-- 2) Eski kullanıcı adı rezervasyonu (90 gün kimse alamaz)
create table if not exists public.username_reservations (
  username text primary key,
  former_user_id uuid not null references auth.users(id) on delete cascade,
  reserved_until timestamptz not null
);
alter table public.username_reservations enable row level security;
revoke all on public.username_reservations from anon, authenticated;

-- 3) Ad değişikliği bekçisi: kısıtlı hesap değiştiremez, cooldown uygulanır,
--    rezerve/yasaklı adlar reddedilir, geçmiş kaydedilir.
create or replace function public.guard_profile_name_change()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare last_change timestamptz;
begin
  if old.is_suspended and (new.username is distinct from old.username or new.display_name is distinct from old.display_name) then
    raise exception 'Hesabın kısıtlıyken ad değiştiremezsin.';
  end if;

  if new.username is distinct from old.username then
    select max(created_at) into last_change from public.name_changes
      where user_id = old.id and field = 'username';
    if last_change is not null and last_change > now() - interval '30 days' then
      raise exception 'Kullanıcı adını en fazla 30 günde bir değiştirebilirsin.';
    end if;
    if new.username !~ '^[a-z0-9_]{3,20}$' then
      raise exception 'Kullanıcı adı 3-20 karakter olmalı; küçük harf, rakam ve alt çizgi.';
    end if;
    if exists (select 1 from public.username_reservations r
               where r.username = new.username and r.reserved_until > now()
                 and r.former_user_id <> old.id) then
      raise exception 'Bu kullanıcı adı şu an başka bir hesap için rezerve.';
    end if;
    if exists (select 1 from public.flagged_terms t
               where position(lower(t.term) in lower(new.username)) > 0) then
      raise exception 'Bu kullanıcı adı kullanılamaz.';
    end if;
    if old.username is not null then
      insert into public.username_reservations (username, former_user_id, reserved_until)
        values (old.username, old.id, now() + interval '90 days')
        on conflict (username) do update
          set reserved_until = excluded.reserved_until, former_user_id = excluded.former_user_id;
    end if;
    insert into public.name_changes (user_id, field, old_value, new_value)
      values (old.id, 'username', old.username, new.username);
  end if;

  if new.display_name is distinct from old.display_name then
    select max(created_at) into last_change from public.name_changes
      where user_id = old.id and field = 'display_name';
    if last_change is not null and last_change > now() - interval '7 days' then
      raise exception 'Görünen adını en fazla 7 günde bir değiştirebilirsin.';
    end if;
    if exists (select 1 from public.flagged_terms t
               where position(lower(t.term) in lower(new.display_name)) > 0) then
      raise exception 'Bu görünen ad kullanılamaz.';
    end if;
    insert into public.name_changes (user_id, field, old_value, new_value)
      values (old.id, 'display_name', old.display_name, new.display_name);
  end if;

  return new;
end;
$$;
revoke all on function public.guard_profile_name_change() from public;

drop trigger if exists trg_guard_profile_name on public.profiles;
create trigger trg_guard_profile_name before update on public.profiles
  for each row execute function public.guard_profile_name_change();

-- 4) Yeni kayıtlarda rezerve ad seçilemesin (signup trigger'ı güncelle)
create or replace function public.handle_new_user_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  base_username text;
  final_username text;
  display_name text;
  counter int := 0;
  max_attempts int := 20;
begin
  if exists (select 1 from public.profiles where id = new.id) then
    return new;
  end if;

  base_username := lower(regexp_replace(coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1), 'user'), '[^a-z0-9_]', '', 'g'));
  if length(base_username) < 3 then
    base_username := 'user';
  end if;
  final_username := base_username;

  while (exists (select 1 from public.profiles where username = final_username)
         or exists (select 1 from public.username_reservations where username = final_username and reserved_until > now()))
        and counter < max_attempts loop
    counter := counter + 1;
    final_username := base_username || '_' || counter::text;
  end loop;

  display_name := coalesce(new.raw_user_meta_data->>'display_name', new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', split_part(new.email, '@', 1), 'Halka kullanıcısı');

  insert into public.profiles (
    id,
    username,
    display_name,
    accepted_terms_version,
    accepted_privacy_version,
    accepted_community_version
  ) values (
    new.id,
    final_username,
    display_name,
    coalesce(new.raw_user_meta_data->>'terms_version', '2026-10-11-v1'),
    coalesce(new.raw_user_meta_data->>'privacy_version', '2026-10-11-v1'),
    coalesce(new.raw_user_meta_data->>'community_rules_version', '2026-10-11-v1')
  )
  on conflict (id) do nothing;

  return new;
end;
$$;
revoke all on function public.handle_new_user_profile() from public, anon, authenticated;
grant execute on function public.handle_new_user_profile() to supabase_auth_admin;

-- 5) Admin: eski ad dahil kullanıcı bulma + geçmiş görme
create or replace function public.admin_user_history(p_username text)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  uid uuid;
  uname text;
  prof record;
  history jsonb;
begin
  if not public.is_current_user_admin() then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;
  uname := lower(btrim(regexp_replace(coalesce(p_username, ''), '^@+', '')));

  select id into uid from public.profiles where username = uname;
  if uid is null then
    select former_user_id into uid from public.username_reservations
      where username = uname order by reserved_until desc limit 1;
  end if;
  if uid is null then
    select user_id into uid from public.name_changes
      where field = 'username' and lower(old_value) = uname
      order by created_at desc limit 1;
  end if;
  if uid is null then
    raise exception 'Bu adla (güncel veya eski) bir hesap bulunamadı.';
  end if;

  select id, username, display_name, is_suspended into prof from public.profiles where id = uid;
  select coalesce(jsonb_agg(jsonb_build_object(
      'field', nc.field, 'old', nc.old_value, 'new', nc.new_value, 'at', nc.created_at
    ) order by nc.created_at desc), '[]'::jsonb)
    into history
    from public.name_changes nc where nc.user_id = uid;

  return jsonb_build_object(
    'id', prof.id,
    'username', prof.username,
    'display_name', prof.display_name,
    'is_suspended', prof.is_suspended,
    'changes', history
  );
end;
$$;
revoke all on function public.admin_user_history(text) from public;
grant execute on function public.admin_user_history(text) to authenticated;

-- 6) Admin: doğrudan hesap kısıtlama / kaldırma
create or replace function public.admin_set_suspension(target_user uuid, suspend boolean, notes text default '')
returns jsonb
language plpgsql security definer set search_path = ''
as $$
begin
  if not public.is_current_user_admin() then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;
  if target_user is null or not exists (select 1 from public.profiles where id = target_user) then
    raise exception 'Kullanıcı bulunamadı.';
  end if;
  update public.profiles set is_suspended = suspend where id = target_user;
  insert into public.moderation_actions (admin_id, action, target_type, target_id, notes)
    values (auth.uid(), case when suspend then 'suspend_user' else 'restore_user' end,
            'user', target_user::text, left(coalesce(notes, ''), 1000));
  return jsonb_build_object('ok', true);
end;
$$;
revoke all on function public.admin_set_suspension(uuid, boolean, text) from public;
grant execute on function public.admin_set_suspension(uuid, boolean, text) to authenticated;

