-- HALKA moderation MVP: reports, admin access, suspension and audit history.

alter table public.profiles
  add column if not exists is_suspended boolean not null default false;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  added_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;

create table if not exists public.content_reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references auth.users(id) on delete cascade,
  target_type text not null check (target_type in ('post', 'comment')),
  target_id text not null,
  target_author_id uuid not null references auth.users(id) on delete cascade,
  reason text not null check (reason in ('spam', 'harassment', 'copyright', 'unsafe', 'other')),
  details text not null default '' check (length(details) <= 1000),
  status text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (reporter_id, target_type, target_id)
);
create index if not exists content_reports_status_created_idx
  on public.content_reports(status, created_at desc);

create table if not exists public.moderation_actions (
  id bigint generated by default as identity primary key,
  admin_id uuid not null references auth.users(id) on delete restrict,
  report_id uuid references public.content_reports(id) on delete set null,
  action text not null check (action in ('resolve', 'dismiss', 'remove_content', 'suspend_user', 'restore_user')),
  target_type text not null,
  target_id text not null,
  notes text not null default '' check (length(notes) <= 1000),
  created_at timestamptz not null default now()
);
create index if not exists moderation_actions_created_idx
  on public.moderation_actions(created_at desc);

alter table public.content_reports enable row level security;
alter table public.moderation_actions enable row level security;
revoke all on public.admin_users, public.content_reports, public.moderation_actions from anon, authenticated;
grant select on public.content_reports, public.moderation_actions to authenticated;

create or replace function public.is_current_user_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users a
    where a.user_id = (select auth.uid())
  );
$$;
revoke all on function public.is_current_user_admin() from public;
grant execute on function public.is_current_user_admin() to authenticated;

create or replace function public.current_user_can_use_app()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_current_user_admin()
    or not exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid()) and p.is_suspended
    );
$$;
revoke all on function public.current_user_can_use_app() from public;
grant execute on function public.current_user_can_use_app() to authenticated;

create or replace function public.can_view_profile(target_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_current_user_admin()
    or (
      not exists (select 1 from public.profiles p where p.id = target_user_id and p.is_suspended)
      and (
        (select auth.uid()) = target_user_id
        or exists (
          select 1 from public.profiles p
          where p.id = target_user_id and p.profile_visibility = 'public'
        )
        or (
          (select auth.uid()) is not null
          and exists (
            select 1 from public.conversation_members mine
            join public.conversation_members theirs using (conversation_id)
            where mine.user_id = (select auth.uid()) and theirs.user_id = target_user_id
          )
        )
      )
    );
$$;
revoke all on function public.can_view_profile(uuid) from public;
grant execute on function public.can_view_profile(uuid) to anon, authenticated;

drop policy if exists "Admins can read content reports" on public.content_reports;
create policy "Admins can read content reports" on public.content_reports
  for select to authenticated using (public.is_current_user_admin());

drop policy if exists "Admins can read moderation history" on public.moderation_actions;
create policy "Admins can read moderation history" on public.moderation_actions
  for select to authenticated using (public.is_current_user_admin());

do $$
declare
  table_name text;
  protected_tables text[] := array[
    'posts', 'chapters', 'comments', 'likes', 'comment_likes',
    'conversations', 'conversation_members', 'messages', 'legal_acceptances'
  ];
begin
  foreach table_name in array protected_tables loop
    if to_regclass(format('public.%I', table_name)) is not null then
      execute format('drop policy if exists %I on public.%I', 'Suspended accounts cannot use app data', table_name);
      execute format(
        'create policy %I on public.%I as restrictive for all to authenticated using (public.current_user_can_use_app()) with check (public.current_user_can_use_app())',
        'Suspended accounts cannot use app data', table_name
      );
    end if;
  end loop;
end $$;

drop policy if exists "Suspended accounts cannot change profiles" on public.profiles;
create policy "Suspended accounts cannot change profiles" on public.profiles
  as restrictive for update to authenticated
  using (public.current_user_can_use_app())
  with check (public.current_user_can_use_app());

drop policy if exists "Suspended accounts cannot upload files" on storage.objects;
create policy "Suspended accounts cannot upload files" on storage.objects
  as restrictive for all to authenticated
  using (public.current_user_can_use_app())
  with check (public.current_user_can_use_app());

create or replace function public.submit_content_report(
  target_type text,
  target_id text,
  report_reason text,
  report_details text default ''
) returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_author uuid;
  new_report_id uuid;
begin
  if auth.uid() is null then raise exception 'Bildirim için giriş yapmalısın.' using errcode = '28000'; end if;
  if target_type not in ('post', 'comment') then raise exception 'Bildirim türü geçersiz.'; end if;
  if report_reason not in ('spam', 'harassment', 'copyright', 'unsafe', 'other') then raise exception 'Bildirim nedeni geçersiz.'; end if;
  if length(coalesce(report_details, '')) > 1000 then raise exception 'Açıklama en fazla 1000 karakter olabilir.'; end if;

  if target_type = 'post' then
    select p.author_id into target_author from public.posts p where p.id = target_id::uuid;
  else
    select c.author_id into target_author from public.comments c where c.id = target_id::bigint;
  end if;
  if target_author is null then raise exception 'Bildirilecek içerik bulunamadı.'; end if;
  if target_author = auth.uid() then raise exception 'Kendi içeriğini bildiremezsin.'; end if;

  insert into public.content_reports(reporter_id, target_type, target_id, target_author_id, reason, details)
  values(auth.uid(), target_type, target_id, target_author, report_reason, trim(coalesce(report_details, '')))
  returning id into new_report_id;
  return new_report_id;
exception when unique_violation then
  raise exception 'Bu içeriği daha önce bildirdin.' using errcode = '23505';
end;
$$;
revoke all on function public.submit_content_report(text, text, text, text) from public, anon;
grant execute on function public.submit_content_report(text, text, text, text) to authenticated;

create or replace function public.admin_handle_report(
  report_id uuid,
  moderation_action text,
  action_notes text default ''
) returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  report_row public.content_reports%rowtype;
begin
  if not public.is_current_user_admin() then raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501'; end if;
  if moderation_action not in ('resolve', 'dismiss', 'remove_content', 'suspend_user', 'restore_user') then
    raise exception 'Yönetim işlemi geçersiz.';
  end if;
  if length(coalesce(action_notes, '')) > 1000 then raise exception 'Not en fazla 1000 karakter olabilir.'; end if;

  select * into report_row from public.content_reports r where r.id = report_id for update;
  if not found then raise exception 'Bildirim bulunamadı.'; end if;

  if moderation_action = 'remove_content' then
    if report_row.target_type = 'post' then
      delete from public.posts where id = report_row.target_id::uuid;
    else
      delete from public.comments where id = report_row.target_id::bigint;
    end if;
  elsif moderation_action = 'suspend_user' then
    update public.profiles set is_suspended = true where id = report_row.target_author_id;
  elsif moderation_action = 'restore_user' then
    update public.profiles set is_suspended = false where id = report_row.target_author_id;
  end if;

  update public.content_reports
  set status = case when moderation_action = 'dismiss' then 'dismissed' else 'resolved' end,
      reviewed_by = auth.uid(), reviewed_at = now()
  where id = report_row.id;

  insert into public.moderation_actions(admin_id, report_id, action, target_type, target_id, notes)
  values(auth.uid(), report_row.id, moderation_action, report_row.target_type, report_row.target_id, trim(coalesce(action_notes, '')));
end;
$$;
revoke all on function public.admin_handle_report(uuid, text, text) from public, anon;
grant execute on function public.admin_handle_report(uuid, text, text) to authenticated;

