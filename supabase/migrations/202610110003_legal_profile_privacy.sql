  for select to authenticated using (auth.uid() = user_id);
revoke all on public.legal_acceptances from anon, authenticated;
grant select on public.legal_acceptances to authenticated;

create or replace function public.record_legal_acceptance(
  accepted_terms_version text,
  accepted_privacy_version text,
  accepted_community_version text
) returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then raise exception 'Giriş yapmalısın.' using errcode = '28000'; end if;
  if accepted_terms_version <> '2026-10-11-v1'
    or accepted_privacy_version <> '2026-10-11-v1'
    or accepted_community_version <> '2026-10-11-v1' then
    raise exception 'Belge sürümleri güncel değil; lütfen sayfayı yenile.' using errcode = '22023';
  end if;
  insert into public.legal_acceptances(user_id, terms_version, privacy_version, community_rules_version, accepted_at)
  values(auth.uid(), accepted_terms_version, accepted_privacy_version, accepted_community_version, now())
  on conflict(user_id, terms_version, privacy_version, community_rules_version) do update set
    accepted_at = excluded.accepted_at;
end;
$$;
revoke all on function public.record_legal_acceptance(text,text,text) from public, anon;
grant execute on function public.record_legal_acceptance(text,text,text) to authenticated;

create or replace function public.log_signup_legal_acceptance()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  metadata jsonb := new.raw_user_meta_data;
begin
  if metadata->>'terms_version' = '2026-10-11-v1'
    and metadata->>'privacy_version' = '2026-10-11-v1'
    and metadata->>'community_rules_version' = '2026-10-11-v1' then
    insert into public.legal_acceptances(user_id, terms_version, privacy_version, community_rules_version)
    values(new.id, metadata->>'terms_version', metadata->>'privacy_version', metadata->>'community_rules_version')
    on conflict(user_id, terms_version, privacy_version, community_rules_version) do nothing;
  end if;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created_log_legal_acceptance on auth.users;
create trigger on_auth_user_created_log_legal_acceptance
  after insert on auth.users for each row execute function public.log_signup_legal_acceptance();
revoke all on function public.log_signup_legal_acceptance() from public, anon, authenticated;

-- Database trigger makes missing/stale consent block email/password account creation
-- even before the optional Auth Hook is configured in the Supabase dashboard.
create or replace function public.require_legal_acceptance_for_email_signup()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  metadata jsonb := new.raw_user_meta_data;
begin
  if new.raw_app_meta_data->>'provider' = 'email'
    and (
      metadata->>'terms_version' is distinct from '2026-10-11-v1'
      or metadata->>'privacy_version' is distinct from '2026-10-11-v1'
      or metadata->>'community_rules_version' is distinct from '2026-10-11-v1'
    ) then
    raise exception 'Hesap açmadan önce Kullanıcı Sözleşmesi, Gizlilik ve KVKK Aydınlatma Metni ile Topluluk Kuralları kabul edilmelidir.'
      using errcode = '42501';
  end if;
  return new;
end;
$$;
drop trigger if exists before_auth_user_require_legal_acceptance on auth.users;
create trigger before_auth_user_require_legal_acceptance
  before insert on auth.users for each row execute function public.require_legal_acceptance_for_email_signup();
revoke all on function public.require_legal_acceptance_for_email_signup() from public, anon, authenticated;
grant execute on function public.require_legal_acceptance_for_email_signup() to supabase_auth_admin;

-- Configure this function under Authentication > Hooks > Before User Created.
-- Google OAuth cannot carry custom signup metadata through signInWithOAuth, so the app
-- requires all document checkboxes before starting Google OAuth and records acceptance
-- after the callback. Email/password signups are checked here server-side.
create or replace function public.hook_require_signup_legal_acceptance(event jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  provider text := event->'user'->'app_metadata'->>'provider';
  metadata jsonb := event->'user'->'user_metadata';
begin
  if provider = 'google' then return '{}'::jsonb; end if;
  if metadata->>'terms_version' = '2026-10-11-v1'
    and metadata->>'privacy_version' = '2026-10-11-v1'
    and metadata->>'community_rules_version' = '2026-10-11-v1' then
    return '{}'::jsonb;
  end if;
  return jsonb_build_object('error', jsonb_build_object(
    'http_code', 400,
    'message', 'Hesap açmadan önce Kullanıcı Sözleşmesi, Gizlilik ve KVKK Aydınlatma Metni ile Topluluk Kuralları kabul edilmelidir.'
  ));
end;
$$;
grant execute on function public.hook_require_signup_legal_acceptance(jsonb) to supabase_auth_admin;
revoke execute on function public.hook_require_signup_legal_acceptance(jsonb) from authenticated, anon, public;

-- A SECURITY DEFINER helper avoids recursive profile RLS lookups and grants private
-- profile visibility only to the owner and people sharing a conversation with them.
create or replace function public.can_view_profile(target_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() = target_user_id
    or exists (
      select 1 from public.profiles p
      where p.id = target_user_id and p.profile_visibility = 'public'
    )
    or (
      auth.uid() is not null
      and exists (
        select 1
        from public.conversation_members mine
        join public.conversation_members theirs using (conversation_id)
        where mine.user_id = auth.uid() and theirs.user_id = target_user_id
      )
    );
$$;
revoke all on function public.can_view_profile(uuid) from public;
grant execute on function public.can_view_profile(uuid) to anon, authenticated;

-- Preserve aggregate counts for visible profiles while excluding private comments.
create or replace view public.comment_like_counts as
  select cl.comment_id, count(*)::bigint as like_count
  from public.comment_likes cl
  join public.comments c on c.id = cl.comment_id
  join public.posts p on p.id = c.post_id
  where public.can_view_profile(p.author_id)
  group by cl.comment_id;

-- Restrictive policies narrow existing SELECT policies instead of replacing their
-- insert/update/delete behavior.
drop policy if exists "Respect profile visibility" on public.profiles;
create policy "Respect profile visibility" on public.profiles
  as restrictive for select to anon, authenticated
  using (public.can_view_profile(id));

drop policy if exists "Respect profile visibility on posts" on public.posts;
create policy "Respect profile visibility on posts" on public.posts
  as restrictive for select to anon, authenticated
  using (public.can_view_profile(author_id));

drop policy if exists "Respect profile visibility on comments" on public.comments;
create policy "Respect profile visibility on comments" on public.comments
  as restrictive for select to anon, authenticated
  using (
    author_id = auth.uid()
    or exists (select 1 from public.posts p where p.id = comments.post_id and public.can_view_profile(p.author_id))
  );

drop policy if exists "Respect profile visibility on likes" on public.likes;
create policy "Respect profile visibility on likes" on public.likes
  as restrictive for select to anon, authenticated
  using (
    user_id = auth.uid()
    or exists (select 1 from public.posts p where p.id = likes.post_id and public.can_view_profile(p.author_id))
  );

drop policy if exists "Respect profile visibility on comment likes" on public.comment_likes;
create policy "Respect profile visibility on comment likes" on public.comment_likes
  as restrictive for select to anon, authenticated
  using (
    user_id = auth.uid()
    or exists (
      select 1 from public.comments c join public.posts p on p.id = c.post_id
      where c.id = comment_likes.comment_id and public.can_view_profile(p.author_id)
    )
  );

create or replace function public.get_profile_stats(target_profile_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  if not public.can_view_profile(target_profile_id) then
    raise exception 'Bu profilin istatistikleri görüntülenemiyor.' using errcode = '42501';
  end if;
  if auth.uid() is distinct from target_profile_id and exists (
    select 1 from public.profiles p where p.id = target_profile_id and p.stats_visibility = 'private'
  ) then
    raise exception 'Bu kullanıcının istatistikleri gizli.' using errcode = '42501';
  end if;
  select jsonb_build_object(
    'posts_count', (select count(*) from public.posts p where p.author_id = target_profile_id),
    'likes_received', (select count(*) from public.likes l join public.posts p on p.id = l.post_id where p.author_id = target_profile_id),
    'comments_count', (select count(*) from public.comments c join public.posts p on p.id = c.post_id where p.author_id = target_profile_id)
  ) into result;
  return result;
end;
$$;
revoke all on function public.get_profile_stats(uuid) from public;
grant execute on function public.get_profile_stats(uuid) to anon, authenticated;

